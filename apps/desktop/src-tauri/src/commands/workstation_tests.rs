use super::validate_workstation;
use serde_json::json;
#[test]
fn rejects_unbounded_audit_and_unconfirmed_retention() {
    assert!(validate_workstation(&json!({"action":"audit","limit":0})).is_err());
    assert!(validate_workstation(&json!({"action":"audit","limit":10,"extra":true})).is_err());
    assert!(validate_workstation(&json!({
        "action":"retention.apply",
        "confirmed":false,
        "activeConversationId":null
    }))
    .is_err());
    assert!(validate_workstation(&json!({
        "action":"context.save",
        "record":{
            "id":"00000000-0000-4000-8000-000000000001",
            "kind":"rule",
            "scope":"global",
            "workspaceId":null,
            "title":"Style",
            "body":"x".repeat(8001),
            "enabled":true
        }
    }))
    .is_err());
    assert!(validate_workstation(&json!({"action":"context.list","kind":"prompt"})).is_ok());
    assert!(validate_workstation(&json!({"action":"context.list","kind":"other"})).is_err());
    assert!(validate_workstation(&json!({"action":"audit","limit":10})).is_ok());
    assert!(validate_workstation(&json!({"action":"mcp.status"})).is_ok());
    assert!(validate_workstation(&json!({
        "action":"mcp.save",
        "config":{
            "id":"00000000-0000-4000-8000-000000000020",
            "name":"Local",
            "enabled":true,
            "credentialRef":null,
            "timeoutMs":15000,
            "transport":"http",
            "url":"http://127.0.0.1:9/mcp"
        }
    }))
    .is_ok());
    assert!(validate_workstation(&json!({
        "action":"mcp.save",
        "config":{
            "id":"00000000-0000-4000-8000-000000000020",
            "name":"Local",
            "enabled":true,
            "transport":"http",
            "url":"http://127.0.0.1:9/mcp",
            "bearer":"secret-token"
        }
    }))
    .is_err());
    assert!(validate_workstation(&json!({
        "action":"mcp.connect",
        "id":"00000000-0000-4000-8000-000000000020",
        "approved":true
    }))
    .is_ok());
    assert!(validate_workstation(&json!({
        "action":"mcp.connect",
        "id":"00000000-0000-4000-8000-000000000020",
        "approved":false
    }))
    .is_err());
    assert!(validate_workstation(&json!({
        "action":"context.save",
        "record":{
            "id":"00000000-0000-4000-8000-000000000001",
            "kind":"prompt",
            "scope":"global",
            "workspaceId":null,
            "title":"Reuse",
            "body":"Prefer small modules.",
            "enabled":true
        }
    }))
    .is_ok());
}
